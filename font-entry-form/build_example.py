# 这就是"字符集白名单"：UI 用到的每个码位都必须能在这份声明里找到（PLAYBOOK §4.4 断言）。
FONT_CHARS = "".join(chr(cp) for cp in range(0x20, 0x7F)) + (
    "字体示例中文渲染正常没有豆腐块标点符号：，。！？（）"
    "你好世界这是经验库沉淀的正确条目形态引擎范围码位"
    "黑白体简体字符集提取消灭豆腐同一件两个为空"
)
FONT_FILE = "fonts/simhei-subset.ttf"   # 相对工程目录（P-0035：必须存相对路径）


def font_entry(name, size, description):
    """EEZ LVGL 字体条目 —— 0.29 的正确形态（P-0125 A/B/C 对照实测定论）。

    四个要点缺一不可：
    1. renderingEngine: "LVGL"          （缺了 → 画布/Run 豆腐 + 点 Fonts 面板崩）
    2. 中文码位进 lvglRanges（数字表字符串）  （只在旧 glyphs 列表里写 → 不收字形）
    3. lvglGlyphs = {encodings:[{from,to}...], symbols: ""}
    4. glyphs: []                        （旧形态字段，留空）
    """
    cps = sorted({ord(c) for c in FONT_CHARS})
    encodings, ranges = [], []
    start = prev = cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        encodings.append({"from": start, "to": prev})
        ranges.append(str(start) if start == prev else "%d-%d" % (start, prev))
        start = prev = cp
    encodings.append({"from": start, "to": prev})
    ranges.append(str(start) if start == prev else "%d-%d" % (start, prev))
    return {
        "objID": oid(),
        "name": name,
        "description": description,
        "renderingEngine": "LVGL",
        "source": {"objID": oid(), "filePath": FONT_FILE, "size": size},
        "bpp": 4,
        "threshold": 128,
        "glyphs": [],
        "screenOrientation": "all",
        "alwaysBuild": False,
        "lvglRanges": ",".join(ranges),
        "lvglSymbols": "",
        "lvglAdditionalSources": [],
        "lvglGlyphs": {"encodings": encodings, "symbols": ""},
    }



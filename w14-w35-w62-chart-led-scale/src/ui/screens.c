void tick_screen_main() {
    void *flowState = getFlowState(0, 0);
    (void)flowState;
    {
        uint32_t new_val = evalUnsignedIntegerProperty(flowState, 8, 3, "Failed to evaluate Color in Led widget");
        new_val = lv_color_to_u32(lv_color_hex(new_val));
        uint32_t cur_val = lv_color_to_u32(((lv_led_t *)objects.led_color)->color);
        if (new_val != cur_val) {
            tick_value_change_obj = objects.led_color;
            lv_led_set_color(objects.led_color, lv_color_hex(new_val));
            tick_value_change_obj = NULL;
        }
    }
    {
        int32_t new_val = evalIntegerProperty(flowState, 9, 3, "Failed to evaluate Brightness in Led widget");
        if (new_val < 0) new_val = 0;
        else if (new_val > 255) new_val = 255;
        int32_t cur_val = lv_led_get_brightness(objects.led_bright);
        if (new_val != cur_val) {
            tick_value_change_obj = objects.led_bright;
            lv_led_set_brightness(objects.led_bright, new_val);
            tick_value_change_obj = NULL;
        }
    }
}

typedef void (*tick_screen_func_t)();
tick_screen_func_t tick_screen_funcs[] = {
    tick_screen_main,
};
void tick_screen(int screen_index) {
    if (screen_index >= 0 && screen_index < 1) {
        tick_screen_funcs[screen_index]();
    }
}
void tick_screen_by_id(enum ScreensEnum screenId) {
    tick_screen(screenId - 1);
}


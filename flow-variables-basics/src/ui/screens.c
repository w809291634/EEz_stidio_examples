void tick_screen_main() {
    void *flowState = getFlowState(0, 0);
    (void)flowState;
    {
        const char *new_val = evalTextProperty(flowState, 3, 3, "Failed to evaluate Text in Label widget");
        const char *cur_val = lv_label_get_text(objects.val_count);
        if (strcmp(new_val, cur_val) != 0) {
            tick_value_change_obj = objects.val_count;
            lv_label_set_text(objects.val_count, new_val);
            tick_value_change_obj = NULL;
        }
    }
    {
        const char *new_val = evalTextProperty(flowState, 4, 3, "Failed to evaluate Text in Label widget");
        const char *cur_val = lv_label_get_text(objects.val_tpl);
        if (strcmp(new_val, cur_val) != 0) {
            tick_value_change_obj = objects.val_tpl;
            lv_label_set_text(objects.val_tpl, new_val);
            tick_value_change_obj = NULL;
        }
    }
    {
        const char *new_val = evalTextProperty(flowState, 6, 3, "Failed to evaluate Text in Label widget");
        const char *cur_val = lv_label_get_text(objects.val_status);
        if (strcmp(new_val, cur_val) != 0) {
            tick_value_change_obj = objects.val_status;
            lv_label_set_text(objects.val_status, new_val);
            tick_value_change_obj = NULL;
        }
    }
    {
        int32_t new_val = evalIntegerProperty(flowState, 8, 3, "Failed to evaluate Value in Bar widget");
        int32_t cur_val = lv_bar_get_value(objects.bar_count);
        if (new_val != cur_val) {
            tick_value_change_obj = objects.bar_count;
            lv_bar_set_value(objects.bar_count, new_val, LV_ANIM_OFF);
            tick_value_change_obj = NULL;
        }
    }
    {
        int32_t new_val = evalIntegerProperty(flowState, 10, 3, "Failed to evaluate Value in Slider widget");
        int32_t cur_val = lv_slider_get_value(objects.sld_count);
        if (new_val != cur_val) {
            tick_value_change_obj = objects.sld_count;
            lv_slider_set_value(objects.sld_count, new_val, LV_ANIM_OFF);
            tick_value_change_obj = NULL;
        }
    }
}

typedef void (*tick_screen_func_t)();
tick_screen_func_t tick_screen_funcs[] = {
    tick_screen_main,
};
void tick_screen(int screen_index) {
    if (screen_index >= 0 && screen_index < 1) {
        tick_screen_funcs[screen_index]();
    }
}
void tick_screen_by_id(enum ScreensEnum screenId) {
    tick_screen(screenId - 1);
}

